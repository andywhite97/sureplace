// jsdom does not implement the browser's native modal focus/inert behavior.
// Browser QA verifies those behaviors; unit tests simulate only dialog visibility.
export function installNativeDialogStubs() {
  Object.defineProperty(HTMLDialogElement.prototype, 'showModal', {
    configurable: true,
    value: function (this: HTMLDialogElement) {
      this.setAttribute('open', '');
    },
  });
  Object.defineProperty(HTMLDialogElement.prototype, 'close', {
    configurable: true,
    value: function (this: HTMLDialogElement) {
      this.removeAttribute('open');
    },
  });
}
